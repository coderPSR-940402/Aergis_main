"""Offline security and verification contract tests (no network access)."""
import hashlib
import io
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch
import urllib.error

import verify_dependency_bootstrap as verifier

BODY = b'official artifact bytes'
DIGEST = hashlib.sha256(BODY).hexdigest()


def metadata(config='', digest=DIGEST, filename='lib-1.0.jar'):
    return f'''<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
    <configuration><verify-metadata>true</verify-metadata><verify-signatures>false</verify-signatures>{config}</configuration>
    <components><component group="org.example" name="lib" version="1.0"><artifact name="{filename}"><sha256 value="{digest}" origin="Generated by Gradle"/></artifact></component></components></verification-metadata>'''


class VerificationTests(unittest.TestCase):
    def parse(self, xml):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'candidate.xml'
            path.write_text(xml)
            return verifier.parse_metadata(path)

    def test_valid_metadata_has_exact_path_and_hash(self):
        entries = self.parse(metadata())
        self.assertEqual(len(entries), 1)
        self.assertEqual(entries[0].path, 'org/example/lib/1.0/lib-1.0.jar')
        self.assertEqual(entries[0].sha256, DIGEST)

    def test_bypasses_and_disabled_metadata_fail_closed(self):
        for config in ('<trusted-artifacts/>', '<ignored-keys/>', '<trusted-keys/>', '<key-servers/>'):
            with self.subTest(config=config), self.assertRaises(ValueError):
                self.parse(metadata(config))
        with self.assertRaises(ValueError):
            self.parse(metadata().replace('<verify-metadata>true', '<verify-metadata>false'))

    def test_hashes_must_be_one_exact_sha256(self):
        for xml in (metadata(digest='abc'), metadata().replace('</artifact>', '<sha256 value="' + DIGEST + '"/></artifact>'), metadata().replace('sha256', 'sha1')):
            with self.subTest(xml=xml), self.assertRaises(ValueError):
                self.parse(xml)

    def test_unsafe_coordinates_and_duplicate_entries_fail_closed(self):
        for filename in ('../lib.jar', 'a%2fb.jar', 'x?token=secret', 'x\\y.jar'):
            with self.subTest(filename=filename), self.assertRaises(ValueError):
                self.parse(metadata(filename=filename))
        xml = metadata()
        component = xml[xml.index('<component group'):xml.index('</components>')]
        with self.assertRaises(ValueError):
            self.parse(xml.replace('</components>', component + '</components>'))
        with self.assertRaises(ValueError):
            self.parse(metadata().replace('org.example', 'org..example'))

    def test_external_entities_and_empty_candidates_fail(self):
        with self.assertRaises(ValueError):
            self.parse('<!DOCTYPE x [<!ENTITY x SYSTEM "file:///etc/passwd">]>' + metadata())
        with self.assertRaises(ValueError):
            self.parse(metadata().replace('<components>', '<components/> <unexpected>').replace('</components>', '</unexpected>'))

    def test_verified_artifact_is_streamed_from_canonical_repository(self):
        entry = self.parse(metadata())[0]
        urls = []
        def fetch(url):
            urls.append(url)
            return DIGEST
        result = verifier.verify_entry(entry, fetch)
        self.assertEqual(result['status'], 'verified')
        self.assertEqual(result['method'], 'download-sha256')
        self.assertTrue(urls[0].startswith('https://dl.google.com/dl/android/maven2/'))

    def test_mismatch_cannot_be_masked_by_later_repository(self):
        result = verifier.verify_entry(self.parse(metadata())[0], lambda url: '0' * 64)
        self.assertEqual(result['status'], 'mismatch')
        self.assertEqual(result['actual_sha256'], '0' * 64)

    def test_missing_repository_falls_back_but_all_missing_fails(self):
        urls = []
        def fetch(url):
            urls.append(url)
            if len(urls) < 3:
                raise urllib.error.HTTPError(url, 404, 'missing', {}, None)
            return DIGEST
        self.assertEqual(verifier.verify_entry(self.parse(metadata())[0], fetch)['status'], 'verified')
        self.assertEqual(len(urls), 3)
        def missing(url):
            raise OSError('unavailable')
        self.assertEqual(verifier.verify_entry(self.parse(metadata())[0], missing)['status'], 'unavailable')

    def test_redirects_allow_only_explicit_https_official_hosts(self):
        for url in ('http://dl.google.com/a', 'https://dl.google.com.evil.test/a', 'https://user:secret@dl.google.com/a', 'https://repo.maven.apache.org:444/a', 'https://github.com/a', 'https://127.0.0.1/a'):
            with self.subTest(url=url), self.assertRaises(ValueError):
                verifier.validate_url(url)
        verifier.validate_url('https://plugins-artifacts.gradle.org/a.jar')
        redirect = verifier.OfficialRedirectHandler()
        with self.assertRaises(ValueError):
            redirect.redirect_request(None, None, 302, 'redirect', {}, 'https://evil.test/payload')

    def test_download_enforces_size_limit_and_hashes_bytes(self):
        class Response(io.BytesIO):
            headers = {}
        class Opener:
            def open(self, request, timeout):
                return Response(BODY)
        with patch.object(verifier.urllib.request, 'build_opener', return_value=Opener()):
            self.assertEqual(verifier.download_hash(verifier.REPOSITORIES[0] + 'x.jar'), DIGEST)
            with self.assertRaises(OSError):
                verifier.download_hash(verifier.REPOSITORIES[0] + 'x.jar', max_bytes=2)

    def test_settings_fail_on_added_or_removed_repositories(self):
        settings = '''pluginManagement { repositories { google(); mavenCentral(); gradlePluginPortal() } }
        dependencyResolutionManagement { repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
        repositories { google(); mavenCentral() } }
        rootProject.name = "Aergis"
        include(":app")'''
        verifier.validate_settings(settings)
        for text in (settings.replace('google()', 'maven { url = uri("https://evil.test") }', 1), settings.replace('gradlePluginPortal()', ''), settings + '\nmavenLocal()'):
            with self.subTest(text=text), self.assertRaises(ValueError):
                verifier.validate_settings(text)


if __name__ == '__main__':
    unittest.main()
